def build_knowledge_context(topics: list[str] | None = None) -> str:
    """Compact bilingual knowledge block for the assistant's system prompt.

    ``topics`` optionally narrows the block: subset of
    {"ratios", "ifrs_gaap", "rcm", "ias", "reading"}. Default = all,
    which stays well inside a prompt-sized budget (~2.5k tokens).
    """
    wanted = set(topics) if topics else {"ratios", "ifrs_gaap", "rcm", "ias", "reading"}
    lines = ["قاعدة المعرفة المالية المرجعية (اقتبس منها حين تسأل النسب/المعايير/المخاطر):"]

    if "ratios" in wanted:
        for r in RATIO_GUIDANCE:
            lines.append(f"- {r['ar']}")
    if "reading" in wanted:
        for p in READING_PRINCIPLES:
            lines.append(f"- {p}")
    if "ifrs_gaap" in wanted:
        lines.append("- مقارنة IFRS ↔ US GAAP (اختصار أهم 8 محاور):")
        for row in IFRS_VS_GAAP[:8]:
            lines.append(f"  · {row['topic']}: IFRS = {row['ifrs']} | US GAAP = {row['gaap']}")
    if "rcm" in wanted:
        lines.append(f"- {RCM_FRAMEWORKS}")
        lines.append("- مختارات مصفوفة المخاطر والرقابة (خطر → رقابة):")
        for h in RCM_HIGHLIGHTS:
            lines.append(f"  · {h['risk']} ({h['desc']}) → {h['control']}")
    if "ias" in wanted:
        lines.append("- معايير IAS/IFRS الشائعة: " + "؛ ".join(IAS_INDEX))

    lines.append(_SOURCES_LINE)
    return "\n".join(lines)
