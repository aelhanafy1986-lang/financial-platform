# ---------------------------------------------------------------------------
# downloads availability summary (live counts of the user's own analyses)
# ---------------------------------------------------------------------------

def downloads_availability(paid: bool, n_analyses: int, n_comparable: int) -> dict:
    """What the signed-in user can download right now, per artifact kind.
    ``n_comparable`` = analyses count when N >= 2 (comparison needs a pair)."""
    return {
        "paid": paid,
        "can_download": paid and n_analyses > 0,
        "report_pdf": n_analyses if paid else 0,
        "pptx": n_analyses if paid else 0,
        "excel": n_analyses if paid else 0,
        "bi_pack": n_analyses if paid else 0,
        "comparison_pdf": max(0, n_comparable - 1) if paid else 0,
        "statements_version": n_analyses if paid else 0,
        "invoices": paid,
    }
